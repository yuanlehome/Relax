"""Keep Docker's derived Linux Unix socket paths within
sockaddr_un.sun_path."""

from __future__ import annotations

import os
import sys
import tempfile
import uuid
from pathlib import Path


SOCKET_SUFFIXES = (
    "docker.sock",
    "exec/containerd/containerd.sock",
    "exec/containerd/containerd-debug.sock",
    "exec/containerd/containerd.sock.ttrpc",
)
MAX_SOCKET_PATH_BYTES = 107  # Linux sun_path is 108 bytes, including its terminator.


def validate_oci_root(root: str | Path) -> str:
    resolved = Path(root).expanduser().resolve()
    longest = max(len(os.fsencode(resolved / suffix)) for suffix in SOCKET_SUFFIXES)
    if longest > MAX_SOCKET_PATH_BYTES:
        raise ValueError(
            f"OCI_ROOT produces a {longest}-byte Unix socket path; Linux allows at most "
            f"{MAX_SOCKET_PATH_BYTES}. Set OCI_ROOT to a shorter node-local directory."
        )
    return str(resolved)


def default_oci_root() -> str:
    # One short root is generated by the driver and shared with all node actors.
    # Experiment names and cloud paths can be arbitrarily long.
    return validate_oci_root(Path(tempfile.gettempdir()) / f"harbor-{uuid.uuid4().hex}")


if __name__ == "__main__":
    validate_oci_root(sys.argv[1])
